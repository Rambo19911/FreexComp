using CommunityToolkit.Mvvm.ComponentModel;
using FreexComp.Ide.Core.Commands;
using FreexComp.Ide.Core.Composition;
using FreexComp.Ide.Core.Menus;
using FreexComp.Ide.Core.Models;
using FreexComp.Ide.Core.Settings;

namespace FreexComp.Ide.Core.ViewModels;

/// <summary>
/// The main window (main-window.md §1): one property per region view-model. Regions not listed here (docks,
/// status-bar fields) arrive with their tasks (I-022, I-027).
/// </summary>
public sealed class MainWindowViewModel : ObservableObject
{
    private readonly IdeServices _services;

    public MainWindowViewModel(IdeServices services)
    {
        ArgumentNullException.ThrowIfNull(services);
        _services = services;
        DocumentArea = new DocumentAreaViewModel(services.Commands, services.Keymap, services.Documents);
        Layout = services.Layout.Layout;
        Layout.DocumentArea = DocumentArea;
        StatusBar = new StatusBarViewModel(services.Status, services.Commands, services.Settings, services.Documents, services.State, services.Projects,
            services.Build, services.Messages);
        services.State.Changed += (_, _) => OnPropertyChanged(nameof(Title)); // UI-WIN-033
        Layout.IsStatusBarShown = StatusBar.IsVisible;
        StatusBar.PropertyChanged += (_, e) =>
        {
            if (e.PropertyName == nameof(StatusBarViewModel.IsVisible))
            {
                Layout.IsStatusBarShown = StatusBar.IsVisible;
            }
        };
        MainMenu = MainMenuModel.Build(services.Commands,
            new CompositeMenuSource(new RecentMenuSource(services.RecentItems), new ProjectMenuSource(services.Projects)));
        ToolBars = ToolBarRowModel.Build(services.Commands, services.Settings, services.ImplementedPhase);
        ProjectCombos.Attach(ToolBars, services.Projects, services.State, services.Commands);
        ToolBarContextMenu = ToolBarRowModel.BuildContextMenu(services.Commands);
        if (services.DesignerShell is { } designer && ToolBars.FirstOrDefault(t => t.Name == ToolBarDefinitions.Designer.Name) is { } designerBar)
        {
            // UI-TB-004 (I-130): the Designer toolbar while a Design view is the active document view.
            designerBar.HasContext = designer.IsDesignActive;
            designer.IsDesignActiveChanged += (_, _) => designerBar.HasContext = designer.IsDesignActive;
        }

        if (services.DebugShell is { } debugShell && ToolBars.FirstOrDefault(t => t.Name == ToolBarDefinitions.Debug.Name) is { } debugBar)
        {
            // UI-TB-004 (I-133): the Debug toolbar while a debug session exists or the Debug profile is active.
            debugBar.HasContext = debugShell.HasToolBarContext;
            debugShell.HasToolBarContextChanged += (_, _) => debugBar.HasContext = debugShell.HasToolBarContext;
        }

        services.Documents.ActiveDocumentChanged += (_, _) => FollowTitleSource(services.Documents.ActiveDocument);
        services.Projects.ProjectChanged += (_, _) => OnPropertyChanged(nameof(Title));
        services.Settings.Changed += (_, e) =>
        {
            if (e.Key == SettingsCatalog.AppearanceShowFullPathInTitle.Name)
                OnPropertyChanged(nameof(Title));
        };
        FollowTitleSource(services.Documents.ActiveDocument);
    }

    /// <summary>The quick-pick popup of the main window (Go to File, Command Palette).</summary>
    public Popups.QuickPickHost QuickPick => _services.QuickPick;

    /// <summary>The services' clock, for view behaviours that time user input (list type-ahead, UI-A11Y-007).</summary>
    public Platform.IClock Clock => _services.Clock;

    private DocumentViewModel? _titleSource;

    private void FollowTitleSource(DocumentViewModel? document)
    {
        if (_titleSource is not null)
            _titleSource.PropertyChanged -= OnTitleSourceChanged;
        _titleSource = document;
        if (document is not null)
            document.PropertyChanged += OnTitleSourceChanged;
        OnPropertyChanged(nameof(Title));
    }

    private void OnTitleSourceChanged(object? sender, System.ComponentModel.PropertyChangedEventArgs e)
    {
        if (e.PropertyName is nameof(DocumentViewModel.Title) or nameof(DocumentViewModel.FilePath))
            OnPropertyChanged(nameof(Title));
    }

    /// <summary>UI-TB-004: context menu of the toolbar row.</summary>
    public IReadOnlyList<MenuItemModel> ToolBarContextMenu { get; }

    /// <summary>Region 3: the toolbars in row order (toolbars.md).</summary>
    public IReadOnlyList<ToolBarModel> ToolBars { get; }

    /// <summary>Region 2: the menu bar (menus.md), generated by the view.</summary>
    public IReadOnlyList<MenuItemModel> MainMenu { get; }

    /// <summary>
    /// UI-WIN-030/031 (main-window.md §4): the subject is the open project's name (the <c>.pproj</c> path with
    /// <c>appearance.showFullPathInTitle</c>), else the active document (its full path with that setting), followed by
    /// the IDE state when it is not Idle (UI-WIN-033).
    /// </summary>
    public string Title
    {
        get
        {
            var fullPath = _services.Settings.Get(SettingsCatalog.AppearanceShowFullPathInTitle);
            var subject = _services.Projects.Project is { } project ? (fullPath ? project.FilePath : project.Name)
                : _titleSource is null or WelcomeDocumentViewModel ? null // the Welcome page is no file (main-window.md §4)
                : fullPath ? _titleSource.FilePath ?? _titleSource.Title
                : _titleSource.Title;
            return WindowTitle.Format(subject, _services.State.Current.State);
        }
    }

    public DocumentAreaViewModel DocumentArea { get; }

    /// <summary>Region 8 (main-window.md §5).</summary>
    public StatusBarViewModel StatusBar { get; }

    /// <summary>Regions 4–7: the docks around the document area (main-window.md §2).</summary>
    public LayoutViewModel Layout { get; }

    /// <summary>IDE-ARCH-043: a key pressed anywhere in the main window; true when it was consumed.</summary>
    public bool HandleKey(KeyGesture gesture) => _services.Commands.HandleKey(gesture);

    /// <summary>IDE-ARCH-042: keyboard focus moved.</summary>
    public void UpdateFocus(FocusState state) => _services.FocusTracker.Update(state);

    /// <summary>IDE-ARCH-043: the keys the focused element handles itself (the design surface's, D-080).</summary>
    public void SetLocalKeys(IReadOnlyCollection<KeyGesture> keys) => _services.FocusTracker.SetLocalKeys(keys);

    /// <summary>The focused element's own command state changed (e.g. a TextBox selection): re-query CanExecute.</summary>
    public void InvalidateCommands() => _services.Commands.InvalidateCanExecute();

    /// <summary>IDE-P1-110 (b): the main window was activated; every open file is re-checked for external changes.</summary>
    public void OnActivated()
    {
        _services.FileChanges.CheckAll();
        _services.Frames?.Refresh(); // DSG-FD-104: frame units changed on disk
    }

    /// <summary>IDE-ED-086: the main window was deactivated; the completion and parameter-info popups of the active editor close.</summary>
    public void OnDeactivated()
    {
        if (_services.Documents.ActiveDocument is TextDocumentViewModel document)
        {
            document.Completion?.Close();
            document.ParameterInfo?.Close();
        }
    }

    /// <summary>
    /// IDE-P1-031 / UI-TW-113: files dropped from the OS. Onto the Project Manager with a project open they are added to
    /// it (<c>project.addExistingFile</c>); anywhere else they open like command-line paths (a <c>.pproj</c> opens the
    /// project). Folders are ignored.
    /// </summary>
    public async Task DropFilesAsync(IReadOnlyList<string> paths, bool ontoProjectManager)
    {
        ArgumentNullException.ThrowIfNull(paths);
        var files = paths.Where(p => !_services.FileSystem.DirectoryExists(p)).ToList();
        if (files.Count == 0)
        {
            return;
        }

        if (ontoProjectManager && _services.Projects.Project is not null)
        {
            await _services.Projects.AddExistingFilesAsync(files);
            return;
        }

        await Composition.StartupSequence.OpenPathsAsync(_services, files);
    }

    /// <summary>True once the exit sequence was accepted; the window then closes without asking again.</summary>
    public bool IsExiting => _services.Application.IsExiting;

    /// <summary>UI-WIN-072: the user closes the main window; the same as <c>file.exit</c>.</summary>
    public void RequestExit() => _ = _services.Commands.ExecuteAsync("file.exit");

    /// <summary>UI-WIN-052/053: where the window opens, given the work areas of the current monitors (DIP).</summary>
    public WindowPlacement RestorePlacement(IReadOnlyList<WorkArea> workAreas, WorkArea primary) =>
        WindowPlacementRules.Restore(_services.Layout.WindowPlacement, workAreas, primary);

    /// <summary>UI-WIN-051 (a), UI-WIN-072 step 3: the window closes; its placement and the UI state are saved.</summary>
    public void SaveUiState(WindowPlacement? placement)
    {
        if (placement is not null)
        {
            _services.Layout.WindowPlacement = placement;
        }

        _services.Layout.Save();
    }
}
