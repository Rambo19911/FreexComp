using System.Globalization;
using System.Text;
using System.Text.Json;

namespace FreexComp.MetadataTesting;

/// <summary>One value the generated program prints: <c>Path=Value</c>, with the value the metadata expects there.</summary>
public sealed record DefaultCheck(string Path, string Expected, string Type);

/// <summary>
/// <c>MetadataDefaultsMatchRuntime</c> (metadata-authoring.md §4): from a metadata root, generates the Pascal program
/// <c>MetaDefaults.pas</c> that creates every non-abstract component with <c>Create(nil)</c> and prints, through <c>TypInfo</c>,
/// every property that has a metadata <c>default</c> (sub-properties of object properties and of a first collection item
/// included) plus <c>Width</c>/<c>Height</c> for <c>defaultSize</c>; then compares the program's output with the metadata.
/// </summary>
public static class MetadataDefaults
{
    public const string ProgramName = "MetaDefaults";

    /// <summary>The generated program text and the checks it answers, in output order.</summary>
    public static (string Program, List<DefaultCheck> Checks) Generate(MetadataRoot root)
    {
        var checks = new List<DefaultCheck>();
        var body = new StringBuilder();
        foreach (var c in root.Components.Where(c => !c.Abstract))
        {
            body.Append(CultureInfo.InvariantCulture, $"  Start('{c.Class}');\n  try\n    C := {c.Class}.Create(nil);\n    try\n");
            var kind = InheritedString(root, c, "kind");
            if (kind is not ("form" or "nonvisual") && Inherited(root, c, "defaultSize") is { } size)
            {
                foreach (var (prop, key) in new[] { ("Width", "width"), ("Height", "height") })
                {
                    checks.Add(new DefaultCheck($"{c.Class}.{prop}", size.GetProperty(key).GetInt32().ToString(CultureInfo.InvariantCulture), "Integer"));
                    body.Append(CultureInfo.InvariantCulture, $"      Show('{c.Class}.{prop}', C, '{prop}');\n");
                }
            }

            foreach (var p in root.Effective(c, "properties"))
            {
                var name = p["name"].GetString()!;
                var path = $"{c.Class}.{name}";
                var type = p["type"].GetString()!;
                var pkind = p.TryGetValue("kind", out var k) ? k.GetString() : null;
                if (p.TryGetValue("default", out var def))
                {
                    checks.Add(new DefaultCheck(path, type == "Char" ? CharOrdinal(def) : Canonical(def), type));
                    body.Append(CultureInfo.InvariantCulture, $"      Show('{path}', C, '{name}');\n");
                }
                else if (pkind == "object" && root.FindType(c.File, type) is { } ot)
                {
                    var subs = SubDefaults(root, c.File, ot, path, checks);
                    if (subs.Count > 0)
                    {
                        body.Append(CultureInfo.InvariantCulture, $"      O := Sub('{path}', C, '{name}');\n      if O <> nil then\n      begin\n");
                        foreach (var s in subs)
                        {
                            body.Append(CultureInfo.InvariantCulture, $"        Show('{path}.{s}', O, '{s}');\n");
                        }

                        body.Append("      end;\n");
                    }
                }
                else if (pkind == "collection" && p.TryGetValue("itemClass", out var ic) && root.FindType(c.File, ic.GetString()!) is { } it)
                {
                    var itemPath = $"{path}[0]";
                    var subs = SubDefaults(root, c.File, it, itemPath, checks);
                    if (subs.Count > 0)
                    {
                        body.Append(CultureInfo.InvariantCulture, $"      O := Sub('{path}', C, '{name}');\n      if O <> nil then\n      begin\n        O := TCollection(O).Add;\n");
                        foreach (var s in subs)
                        {
                            body.Append(CultureInfo.InvariantCulture, $"        Show('{itemPath}.{s}', O, '{s}');\n");
                        }

                        body.Append("      end;\n");
                    }
                }
            }

            body.Append("    finally\n      C.Free;\n    end;\n  except\n    on E: Exception do\n      WriteLn(Current, ': ', E.ClassName, ': ', E.Message);\n  end;\n");
        }

        var units = root.Files.Select(f => f.Unit).Where(u => u.Length > 0).Distinct(StringComparer.OrdinalIgnoreCase).ToList();
        foreach (var u in new[] { "Graphics", "Controls" })
        {
            if (!units.Contains(u, StringComparer.OrdinalIgnoreCase))
            {
                units.Add(u);
            }
        }

        var program = $$"""
            // generated by the test MetadataDefaultsMatchRuntime from ui-framework/design (metadata-authoring.md section 4)
            program {{ProgramName}};
            { Creates every non-abstract component of the metadata with Create(nil) and prints Path=Value for each property
              the metadata gives a default (and Width/Height for defaultSize). Values: integers in decimal, Char as its
              ordinal, enumerations/Booleans by name, sets as comma-separated names, TColor/TCursor by constant name. }
            uses
              SysUtils, Classes, TypInfo, {{string.Join(", ", units)}};

            var
              Current: string;
              C: TComponent;
              O: TObject;

            procedure Start(const Name: string);
            begin
              Current := Name;
            end;

            procedure Show(const Path: string; Instance: TObject; const PropName: string);
            var
              Info: PPropInfo;
              S: string;
            begin
              Info := GetPropInfo(Instance, PropName);
              if Info = nil then
              begin
                WriteLn(Path, ' (not published)');
                Exit;
              end;
              case Info^.PropType^.Kind of
                tkInteger, tkInt64:
                  if Info^.PropType^.Name = 'TColor' then
                    S := ColorToString(TColor(GetOrdProp(Instance, Info)))
                  else if Info^.PropType^.Name = 'TCursor' then
                    S := CursorToString(TCursor(GetOrdProp(Instance, Info)))
                  else
                    S := IntToStr(GetOrdProp(Instance, Info));
                tkChar, tkWChar:
                  S := IntToStr(GetOrdProp(Instance, Info));
                tkEnumeration:
                  S := GetEnumProp(Instance, Info);
                tkSet:
                  S := GetSetProp(Instance, Info, False);
                tkUString, tkAString, tkSString:
                  S := GetStrProp(Instance, Info);
                tkFloat:
                  S := FloatToStr(GetFloatProp(Instance, Info));
              else
                S := '(kind ' + IntToStr(Ord(Info^.PropType^.Kind)) + ')';
              end;
              WriteLn(Path, '=', S);
            end;

            function Sub(const Path: string; Instance: TObject; const PropName: string): TObject;
            begin
              Result := GetObjectProp(Instance, PropName);
              if Result = nil then
                WriteLn(Path, ' (nil)');
            end;

            begin
            {{body}}end.

            """;
        return (program.ReplaceLineEndings("\n"), checks);
    }

    /// <summary><c>Path: metadata x, runtime y</c> for every check whose printed value differs; extra output lines are problems too.</summary>
    public static List<string> Compare(IReadOnlyList<DefaultCheck> checks, string output)
    {
        var problems = new List<string>();
        var values = new Dictionary<string, string>(StringComparer.Ordinal);
        foreach (var line in output.ReplaceLineEndings("\n").Split('\n', StringSplitOptions.RemoveEmptyEntries))
        {
            var eq = line.IndexOf('=', StringComparison.Ordinal);
            if (eq < 0)
            {
                problems.Add(line);
                continue;
            }

            values[line[..eq]] = line[(eq + 1)..];
        }

        foreach (var check in checks)
        {
            if (!values.TryGetValue(check.Path, out var actual))
            {
                if (!problems.Any(p => p.StartsWith(check.Path.Split('.')[0] + ":", StringComparison.Ordinal) || p.StartsWith(check.Path + " ", StringComparison.Ordinal)))
                {
                    problems.Add($"{check.Path}: metadata {check.Expected}, runtime (not printed)");
                }

                continue;
            }

            if (!Same(check, actual))
            {
                problems.Add($"{check.Path}: metadata {check.Expected}, runtime {actual}");
            }
        }

        return problems;
    }

    private static bool Same(DefaultCheck check, string actual)
    {
        if (check.Type == "Boolean" || check.Type is "TColor" or "TCursor")
        {
            return string.Equals(check.Expected, actual, StringComparison.OrdinalIgnoreCase);
        }

        if (check.Expected.StartsWith('[') && check.Expected.EndsWith(']'))
        {
            var e = check.Expected[1..^1].Split(',', StringSplitOptions.RemoveEmptyEntries).ToHashSet(StringComparer.OrdinalIgnoreCase);
            var a = actual.Split(',', StringSplitOptions.RemoveEmptyEntries).ToHashSet(StringComparer.OrdinalIgnoreCase);
            return e.SetEquals(a);
        }

        return string.Equals(check.Expected, actual, StringComparison.Ordinal);
    }

    /// <summary>The metadata default in the program's canonical form (sets as <c>[a,b]</c>, Char as its ordinal).</summary>
    private static string Canonical(JsonElement def) => def.ValueKind switch
    {
        JsonValueKind.True => "True",
        JsonValueKind.False => "False",
        JsonValueKind.Number => def.GetRawText(),
        JsonValueKind.Array => "[" + string.Join(",", def.EnumerateArray().Select(x => x.GetString())) + "]",
        _ => def.GetString()!,
    };

    /// <summary>The flattened sub-properties of an object type that have a default; adds their checks.</summary>
    private static List<string> SubDefaults(MetadataRoot root, MetadataFile file, JsonElement type, string path, List<DefaultCheck> checks)
    {
        var names = new List<string>();
        foreach (var p in Flatten(root, file, type))
        {
            if (p.TryGetProperty("default", out var def))
            {
                var name = p.GetProperty("name").GetString()!;
                var t = p.GetProperty("type").GetString()!;
                checks.Add(new DefaultCheck($"{path}.{name}", t == "Char" ? CharOrdinal(def) : Canonical(def), t));
                names.Add(name);
            }
        }

        return names;
    }

    private static string CharOrdinal(JsonElement def) =>
        (def.GetString() is { Length: 1 } s ? s[0] : 0).ToString(CultureInfo.InvariantCulture);

    private static List<JsonElement> Flatten(MetadataRoot root, MetadataFile file, JsonElement t)
    {
        var list = t.TryGetProperty("ancestor", out var a) && root.FindType(file, a.GetString()!) is { } parent ? Flatten(root, file, parent) : [];
        foreach (var p in MetadataComponent.Array(t, "properties"))
        {
            var at = list.FindIndex(x => x.GetProperty("name").GetString() == p.GetProperty("name").GetString());
            if (at >= 0)
            {
                list[at] = p;
            }
            else
            {
                list.Add(p);
            }
        }

        return list;
    }

    private static JsonElement? Inherited(MetadataRoot root, MetadataComponent c, string key) =>
        root.Chain(c).Select(k => k.Json.TryGetProperty(key, out var v) ? v : (JsonElement?)null).FirstOrDefault(v => v is not null);

    private static string? InheritedString(MetadataRoot root, MetadataComponent c, string key) =>
        Inherited(root, c, key) is { ValueKind: JsonValueKind.String } v ? v.GetString() : null;
}

/// <summary>
/// <c>Reg_AllClassesRegistered</c> (testing.md §3.6, UIF-002): a generated program that uses every unit with a components file and
/// prints one line per non-abstract metadata class that <c>Classes.GetClass</c> does not return (or returns under another name).
/// </summary>
public static class MetadataRegistration
{
    public const string ProgramName = "MetaRegistered";

    public static string Generate(MetadataRoot root)
    {
        var units = root.Files.Select(f => f.Unit).Where(u => u.Length > 0).Distinct(StringComparer.OrdinalIgnoreCase);
        var body = new StringBuilder();
        foreach (var c in root.Components.Where(c => !c.Abstract))
        {
            body.Append(CultureInfo.InvariantCulture, $"  Check('{c.Class}');\n");
        }

        var program = $$"""
            // generated by the test Reg_AllClassesRegistered from ui-framework/design (testing.md section 3.6)
            program {{ProgramName}};
            uses
              SysUtils, Classes, {{string.Join(", ", units)}};

            var
              Count: Integer;

            procedure Check(const Name: string);
            var
              C: TPersistentClass;
            begin
              Inc(Count);
              C := GetClass(Name);
              if C = nil then
                WriteLn(Name, ': not registered')
              else if C.ClassName <> Name then
                WriteLn(Name, ': GetClass returns ', C.ClassName);
            end;

            begin
              Count := 0;
            {{body}}  WriteLn('checked ', Count);
            end.

            """;
        return program.ReplaceLineEndings("\n");
    }
}
